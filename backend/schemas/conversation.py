from datetime import datetime
from typing import List, Optional
from pydantic import BaseModel, ConfigDict, Field


class CitationItem(BaseModel):
    """Structured verifiable citation linked to retrieved document evidence."""

    citation_id: str = Field(..., description="Evidence identifier cited by the model, e.g., 'E1'")
    document_id: str = Field(..., description="Target document UUID")
    filename: str = Field(..., description="Original PDF filename")
    page_start: int = Field(..., description="Starting 1-based page number")
    page_end: int = Field(..., description="Ending 1-based page number")
    section: str = Field(default="", description="Section or heading title")
    excerpt: str = Field(default="", description="Exact supporting passage text from retrieved child chunk")
    family_title: Optional[str] = Field(default=None, description="Document family title")
    version_number: int = Field(default=1, description="Document version number")
    version_status: str = Field(default="current", description="Version status ('current', 'superseded', 'archived')")
    is_current: bool = Field(default=True, description="Whether this cited version is the active current version")

    model_config = ConfigDict(from_attributes=True)


class ConversationCreateRequest(BaseModel):
    """Schema for initializing a new conversation session."""

    title: Optional[str] = Field(default="New Conversation", max_length=255)
    knowledge_scope: Optional[str] = Field(default="company", description="'company', 'personal', or 'combined'")


class ConversationUpdateRequest(BaseModel):
    """Schema for updating conversation metadata (rename title, change knowledge scope)."""

    title: Optional[str] = Field(default=None, max_length=255)
    knowledge_scope: Optional[str] = Field(default=None, description="'company', 'personal', or 'combined'")


class ConversationResponse(BaseModel):
    """Schema for conversation metadata response."""

    id: str
    workspace_id: str
    user_id: Optional[str] = None
    title: str
    knowledge_scope: str = "company"
    is_active: bool
    attached_document_ids: List[str] = Field(default_factory=list)
    created_at: datetime
    updated_at: datetime

    model_config = ConfigDict(from_attributes=True)


class ConversationAttachmentRequest(BaseModel):
    """Schema for attaching a document to a conversation."""

    document_id: str = Field(..., description="Document UUID to attach")


class ConversationAttachmentResponse(BaseModel):
    """Schema for an individual document attachment on a conversation."""

    id: str
    conversation_id: str
    document_id: str
    original_filename: str
    visibility_scope: str
    created_at: datetime

    model_config = ConfigDict(from_attributes=True)


class ConversationAttachmentListResponse(BaseModel):
    """List of documents attached to a conversation."""

    total: int
    items: List[ConversationAttachmentResponse]


class ConversationListResponse(BaseModel):
    """Paginated conversation list response."""

    total: int
    page: int
    page_size: int
    items: List[ConversationResponse]


class MessageCreateRequest(BaseModel):
    """Schema for submitting a user message to a conversation."""

    content: str = Field(..., min_length=1, description="User question or follow-up query")


class MessageResponse(BaseModel):
    """Schema for an individual conversation message."""

    id: str
    conversation_id: str
    role: str  # 'user' or 'assistant'
    content: str
    citations: Optional[List[CitationItem]] = None
    created_at: datetime

    model_config = ConfigDict(from_attributes=True)


class MessageListResponse(BaseModel):
    """List of messages within a conversation."""

    total: int
    items: List[MessageResponse]


class RAGResponse(BaseModel):
    """Schema for the grounded RAG answer generated by the conversational workflow."""

    conversation_id: str
    message_id: str
    answer: str
    citations: List[CitationItem]
    evidence_sufficient: bool
    response_type: str = Field(
        default="valid_answer",
        description="One of: 'valid_answer', 'llm_not_configured', 'insufficient_evidence', 'documents_indexing', 'retrieval_error', 'llm_error'",
    )
    query_category: Optional[str] = None
    contextualized_query: Optional[str] = None
    validation_issues: Optional[List[str]] = None
    llm_provider_status: Optional[str] = None
    retrieval_time_ms: Optional[float] = None
    llm_time_ms: Optional[float] = None
    total_time_ms: Optional[float] = None
